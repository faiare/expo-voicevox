#!/usr/bin/env node
/**
 * `plugin/src/core/artifacts.generated.ts`（size と sha256 のピン留め表）を作り直す。
 *
 * これがあるおかげで config plugin は prebuild 時に GitHub API を叩かずに済む。
 * GitHub のリリース API には `digest` が入っていることもあるが、古いリリース
 * （open_jtalk v1.11.1 / voicevox_onnxruntime 1.17.3）は null なので、
 * 結局どれも実際にダウンロードして計算するのが確実。キャッシュが効くので 2 回目以降は速い。
 *
 * 使い方:
 *   npm run refresh:artifact-digests
 */

import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const BUILD = path.join(ROOT, 'plugin', 'build');
if (!fs.existsSync(path.join(BUILD, 'core', 'versions.js'))) {
  throw new Error('plugin/build is missing. Run `npx tsc --build plugin` first.');
}

// URL の組み立ては versions.js から直接行う。artifacts.js を経由すると、
// artifacts.js が生成物である artifacts.generated.ts を import しているせいで
// 「生成物が無いと生成できない」循環になるため。
const {
  DEFAULT_VERSIONS,
  iosCoreXcframeworkUrl,
  iosOnnxruntimeXcframeworkUrl,
  androidJavaPackagesUrl,
  androidOnnxruntimeUrl,
  openJtalkDictUrl,
  voiceModelUrl,
} = require(path.join(BUILD, 'core', 'versions.js'));
const { VOICE_MODEL_LICENSE_FILES } = require(path.join(BUILD, 'core', 'setupAssets.js'));
const { ANDROID_ABIS } = require(path.join(BUILD, 'types.js'));
const { createCache } = require(path.join(BUILD, 'core', 'cache.js'));
const { downloadToCache } = require(path.join(BUILD, 'core', 'download.js'));

const OUTPUT = path.join(ROOT, 'plugin', 'src', 'core', 'artifacts.generated.ts');

async function main() {
  const v = DEFAULT_VERSIONS;
  const specs = [
    { label: `voicevox_core.xcframework (${v.core})`, url: iosCoreXcframeworkUrl(v.core) },
    {
      label: `voicevox_onnxruntime.xcframework (${v.onnxruntime.ios})`,
      url: iosOnnxruntimeXcframeworkUrl(v.onnxruntime.ios),
    },
    { label: `voicevoxcore-android (${v.core})`, url: androidJavaPackagesUrl(v.core) },
    ...ANDROID_ABIS.map((abi) => ({
      label: `libvoicevox_onnxruntime.so (${abi}, ${v.onnxruntime.android})`,
      url: androidOnnxruntimeUrl(v.onnxruntime.android, abi),
    })),
    {
      label: `OpenJTalk dictionary (${v.openJtalkDictDirName})`,
      url: openJtalkDictUrl(v.openJtalkDictTag, v.openJtalkDictDirName),
    },
    ...VOICE_MODEL_LICENSE_FILES.map((name) => ({
      label: `VVM ${name} (${v.voiceModel})`,
      url: voiceModelUrl(v.voiceModel, name),
    })),
  ];

  process.stdout.write(`Verifying ${specs.length} artifacts\n`);
  const cache = createCache(ROOT, null);
  const entries = [];

  for (const spec of specs) {
    // sha256 も size も渡さない = 検証せずに計算するだけ。
    const result = await downloadToCache({
      url: spec.url,
      cache,
      sha256: null,
      size: null,
      log: (message) => process.stdout.write(`  ${message}\n`),
    });
    process.stdout.write(
      `  ${spec.label}: ${result.size} bytes${result.cached ? ' (cached)' : ''}\n`
    );
    entries.push({ url: spec.url, size: result.size, sha256: result.sha256 });
  }

  entries.sort((a, b) => a.url.localeCompare(b.url));

  const body = entries
    .map(
      (entry) =>
        `  ${JSON.stringify(entry.url)}: { size: ${entry.size}, sha256: ${JSON.stringify(entry.sha256)} },`
    )
    .join('\n');

  fs.writeFileSync(
    OUTPUT,
    `// Generated by \`npm run refresh:artifact-digests\`. Do not edit by hand.
//
// Pins the size and sha256 of every voicevox_core / ONNX Runtime / OpenJTalk artifact by URL,
// so prebuild can verify downloads without calling the GitHub API.
export const ARTIFACT_DIGESTS: Record<string, { size: number; sha256: string }> = {
${body}
};
`,
    'utf8'
  );

  process.stdout.write(`wrote ${path.relative(ROOT, OUTPUT)}\n`);
}

main().catch((error) => {
  process.stderr.write(`\nFailed to refresh the digest table: ${error.message}\n`);
  process.exitCode = 1;
});
